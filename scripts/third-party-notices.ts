/**
 * Writes THIRD_PARTY_NOTICES: the licences of every npm package that reaches a
 * shipped artefact (the sidecar bundle, the action bundle, the SDK's dependency)
 * with their full licence texts, and the components of the container image.
 * Fails when a package has a licence outside the permissive allowlist.
 * With `--check` nothing is written; the script fails on drift (CI).
 *
 *   pnpm notices [--check]
 */
import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = join(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const ALLOWED = new Set(["MIT", "ISC", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "0BSD"]);
// The shipped packages; their production dependencies are collected transitively.
const SHIPPED = ["packages/sidecar", "packages/release-tools", "packages/sdk"];

interface Manifest {
  name: string;
  version: string;
  license?: string;
  repository?: string | { url?: string };
  dependencies?: Record<string, string>;
}

const found = new Map<string, { manifest: Manifest; dir: string }>();
const problems: string[] = [];

/** node_modules lookup from a directory upwards (exports maps may hide package.json). */
function packageManifest(fromDir: string, name: string): string | null {
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, "node_modules", name, "package.json");
    if (existsSync(candidate)) {
      return realpathSync(candidate);
    }
    const parent = dirname(dir);
    if (parent === dir) {
      return null;
    }
    dir = parent;
  }
}

function collect(fromDir: string, name: string): void {
  if (name.startsWith("@cicd-updater/")) {
    const dir = join(root, "packages", name.slice("@cicd-updater/".length));
    const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as Manifest;
    for (const dependency of Object.keys(manifest.dependencies ?? {})) {
      collect(dir, dependency);
    }
    return;
  }
  const manifestPath = packageManifest(fromDir, name);
  if (!manifestPath) {
    problems.push(`${name} (needed by ${fromDir}) is not installed`);
    return;
  }
  const dir = dirname(manifestPath);
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as Manifest;
  const key = `${manifest.name}@${manifest.version}`;
  if (found.has(key)) {
    return;
  }
  found.set(key, { manifest, dir });
  for (const dependency of Object.keys(manifest.dependencies ?? {})) {
    collect(dir, dependency);
  }
}

for (const pkg of SHIPPED) {
  const dir = join(root, pkg);
  const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as Manifest;
  for (const dependency of Object.keys(manifest.dependencies ?? {})) {
    collect(dir, dependency);
  }
}

function licenceText(dir: string): string | null {
  for (const name of ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license", "COPYING"]) {
    try {
      return readFileSync(join(dir, name), "utf8").trim();
    } catch {
      // next candidate
    }
  }
  return null;
}

const sections: string[] = [];
for (const [key, { manifest, dir }] of [...found.entries()].sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const licence = manifest.license ?? "UNKNOWN";
  if (!ALLOWED.has(licence)) {
    problems.push(`${key}: licence ${licence} is not in the allowlist`);
  }
  const text = licenceText(dir);
  if (!text) {
    problems.push(`${key}: no licence file`);
  }
  const repository =
    typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url;
  sections.push(
    [
      `${manifest.name} ${manifest.version}`,
      `Licence: ${licence}`,
      ...(repository ? [`Source: ${repository.replace(/^git\+/, "")}`] : []),
      "",
      text ?? "",
    ].join("\n"),
  );
}

