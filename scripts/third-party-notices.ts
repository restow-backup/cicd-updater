const content = `${header}\n${"=".repeat(78)}\n\n${sections.join(`\n\n${"-".repeat(78)}\n\n`)}\n\n${"=".repeat(78)}\n\n${image}`;

if (problems.length > 0) {
  for (const problem of problems) {
    console.error(problem);
  }
  process.exit(1);
}
const target = join(root, "THIRD_PARTY_NOTICES");
let current: string | null = null;
try {
  current = readFileSync(target, "utf8");
} catch {
  current = null;
}
if (check) {
  if (current !== content) {
    console.error("THIRD_PARTY_NOTICES is out of date: run pnpm notices");
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES is up to date (${found.size} packages).`);
} else {
  writeFileSync(target, content);
  console.log(`wrote THIRD_PARTY_NOTICES (${found.size} packages)`);
}
